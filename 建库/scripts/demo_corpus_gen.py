def rows(items, meta, start_no):
    out = []
    for i, (chapter, locator, ctype, section, seq, content) in enumerate(items, start_no):
        row = dict(meta)
        row.update({"chapter": chapter, "locator": locator, "chunk_type": ctype,
                    "section": f"{chapter} {section}", "section_seq": seq,
                    "sub_part": "", "line_no": i, "content": content,
                    "src": "demo/corpus.jsonl（虚构演示语料）"})
        out.append(row)
    return out

